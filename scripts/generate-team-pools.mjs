import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, '..');
const poolRoot = path.join(repositoryRoot, 'crests', 'pools');
const outputPath = path.join(repositoryRoot, 'generated-team-pools.js');

const competitions = ['champions', 'europa', 'conference'];
const stages = ['guaranteed', 'playoffs', 'q3', 'q2'];

async function readStage(competition, stage) {
  const directory = path.join(poolRoot, competition, stage);
  let files = [];

  try {
    files = await readdir(directory);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }

  return files
    .filter((file) => file.toLocaleLowerCase('en-US').endsWith('.png'))
    .sort((first, second) => first.localeCompare(second, 'en'))
    .map((file) => file);
}

const manifest = {};

for (const competition of competitions) {
  manifest[competition] = {};
  for (const stage of stages) {
    manifest[competition][stage] = await readStage(competition, stage);
  }
}

const output = `// This file is generated by scripts/generate-team-pools.mjs.
// Move PNG files between pool folders; do not edit this manifest by hand.
(() => {
  'use strict';

  window.UCLDRAW_POOL_MANIFEST = Object.freeze(${JSON.stringify(manifest, null, 2)});
})();
`;

await writeFile(outputPath, output, 'utf8');
console.log(`Generated ${path.relative(repositoryRoot, outputPath)}`);
